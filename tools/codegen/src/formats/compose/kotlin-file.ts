import type { TokenBase } from "../../model/types.ts";

export const KOTLIN_HEADER = "// Generated by tools/codegen from design/source and design/extensions. Do not edit.";

export function kotlinFile(packageName: string, imports: string[], blocks: string[], header: string = KOTLIN_HEADER): string {
  const importLines = [...new Set(imports)].sort().map((name) => `import ${name}`);
  return [header, "", `package ${packageName}`, "", ...(importLines.length > 0 ? [...importLines, ""] : []), blocks.join("\n\n"), ""].join("\n");
}

export function indent(lines: string[], depth = 1): string[] {
  const prefix = "    ".repeat(depth);
  return lines.map((line) => (line === "" ? "" : `${prefix}${line}`));
}

export function block(header: string, body: string[]): string[] {
  if (body.length === 0) {
    return [header];
  }
  return [`${header} {`, ...indent(body), "}"];
}

export function deprecation(token: TokenBase, replacement: (target: string) => string): string[] {
  if (token.deprecated === undefined) {
    return [];
  }
  const target = replacement(token.deprecated.renamedTo);
  return [`@Deprecated("Use ${target}.", ReplaceWith("${target}"))`];
}

export function active<T extends TokenBase>(tokens: T[]): T[] {
  return tokens.filter((token) => token.deprecated === undefined);
}

export function argumentList(name: string, entries: string[], suffix = ""): string[] {
  if (entries.length === 0) {
    return [`${name}()${suffix}`];
  }
  return [`${name}(`, ...indent(entries.map((entry) => `${entry},`)), `)${suffix}`];
}
