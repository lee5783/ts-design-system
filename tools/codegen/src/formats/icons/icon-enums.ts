import type { GeneratedFile } from "../../generate.ts";
import type { IconAsset } from "../../icons/vector-assets.ts";
import { kotlinIdentifier } from "../../transforms/android.ts";
import { swiftIdentifier, swiftString } from "../../transforms/swift.ts";
import { kotlinFile } from "../compose/kotlin-file.ts";
import { block, indent, swiftFile } from "../swift/swift-file.ts";
import { iconCaseName, iconResourceName } from "./asset-files.ts";

export const ICON_CODE_HEADER = "// Generated by tools/codegen from design/assets. Do not edit.";
export const ANDROID_CORE_KOTLIN_DIR = "android/core/src/generated/kotlin";
export const KOTLIN_ICON_PACKAGE = "com.tinysol.designsystem.core.icon";

function pascal(camel: string): string {
  return `${camel.charAt(0).toUpperCase()}${camel.slice(1)}`;
}

export function swiftIconName(icons: IconAsset[]): string {
  const cases = icons.map((icon) => `case ${swiftIdentifier(iconCaseName(icon))} = ${swiftString(icon.name)}`);
  const mirrored = icons.filter((icon) => icon.mirrorsInRTL).map((icon) => `.${swiftIdentifier(iconCaseName(icon))}`);
  const flips =
    mirrored.length === 0
      ? ["false"]
      : ["switch self {", `case ${mirrored.join(", ")}:`, "    true", "default:", "    false", "}"];
  const body = [
    ...cases,
    "",
    ...block("public var assetName: String", ["rawValue"]).split("\n"),
    "",
    ...block("public var flipsForRightToLeftLayoutDirection: Bool", flips).split("\n"),
  ];
  return swiftFile(["Foundation"], [block("public enum TSIconName: String, CaseIterable, Hashable, Sendable", body)], ICON_CODE_HEADER);
}

export function kotlinIconEnum(icons: IconAsset[]): string {
  const entries = icons.map((icon, index) => {
    const separator = index === icons.length - 1 ? "" : ",";
    return `${kotlinIdentifier(pascal(iconCaseName(icon)))}(R.drawable.${iconResourceName(icon)}, ${icon.mirrorsInRTL})${separator}`;
  });
  const header = ["public enum class TSIcon(", ...indent(["public val drawableRes: Int,", "public val autoMirrored: Boolean,"]), ") {"];
  return kotlinFile(KOTLIN_ICON_PACKAGE, ["com.tinysol.designsystem.core.R"], [[...header, ...indent(entries), "}"].join("\n")], ICON_CODE_HEADER);
}

export function swiftIconNameFile(icons: IconAsset[], outputDir: string): GeneratedFile {
  return { path: `${outputDir}/TSIconName.swift`, contents: swiftIconName(icons) };
}

export function kotlinIconFile(icons: IconAsset[], outputDir: string = ANDROID_CORE_KOTLIN_DIR): GeneratedFile {
  return { path: `${outputDir}/${KOTLIN_ICON_PACKAGE.replaceAll(".", "/")}/TSIcon.kt`, contents: kotlinIconEnum(icons) };
}
