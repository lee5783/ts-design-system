import type { GeneratedFile } from "../../generate.ts";
import type { IconAsset, VectorAsset } from "../../icons/vector-assets.ts";
import { parseHexColor } from "../../transforms/css-values.ts";
import { androidArgb, formatNumber } from "../../transforms/android.ts";
import type { ResolvedLogo } from "./asset-files.ts";
import { iconResourceName, logoResourceName } from "./asset-files.ts";

export const ANDROID_CORE_RES_DIR = "android/core/src/generated/res";

export const VECTOR_HEADER = "<!-- Generated by tools/codegen from design/assets. Do not edit. -->";

export function vectorDrawable(asset: VectorAsset, autoMirrored = false): string {
  const attributes = [
    'xmlns:android="http://schemas.android.com/apk/res/android"',
    `android:width="${formatNumber(asset.width)}dp"`,
    `android:height="${formatNumber(asset.height)}dp"`,
    `android:viewportWidth="${formatNumber(asset.viewportWidth)}"`,
    `android:viewportHeight="${formatNumber(asset.viewportHeight)}"`,
    ...(autoMirrored ? ['android:autoMirrored="true"'] : []),
  ];
  const paths = asset.layers.flatMap((layer) => [
    "    <path",
    `        android:fillColor="${androidArgb(parseHexColor(layer.fill).rgba)}"`,
    ...(layer.fillRule === "evenodd" ? ['        android:fillType="evenOdd"'] : []),
    `        android:pathData="${layer.pathData}" />`,
  ]);
  const [first, ...rest] = attributes;
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    VECTOR_HEADER,
    `<vector ${first}`,
    ...rest.map((attribute, index) => `    ${attribute}${index === rest.length - 1 ? ">" : ""}`),
    ...paths,
    "</vector>",
    "",
  ].join("\n");
}

export function androidIconDrawables(icons: IconAsset[], dir: string = ANDROID_CORE_RES_DIR): GeneratedFile[] {
  return icons.map((icon) => ({
    path: `${dir}/drawable/${iconResourceName(icon)}.xml`,
    contents: vectorDrawable(icon, icon.mirrorsInRTL),
  }));
}

export function androidLogoDrawables(logos: ResolvedLogo[], dir: string = ANDROID_CORE_RES_DIR): GeneratedFile[] {
  return logos.flatMap((logo) => {
    const name = logoResourceName(logo.name);
    return [
      { path: `${dir}/drawable/${name}.xml`, contents: vectorDrawable(logo.light) },
      ...(logo.dark === undefined ? [] : [{ path: `${dir}/drawable-night/${name}.xml`, contents: vectorDrawable(logo.dark) }]),
    ];
  });
}
