import type { TokenBase } from "../../model/types.ts";
import { toCamelName } from "../../transforms/naming.ts";
import { swiftIdentifier } from "../../transforms/swift.ts";

export const SWIFT_HEADER = "// Generated by tools/codegen from design/source and design/extensions. Do not edit.";

export function swiftFile(imports: string[], blocks: string[], header: string = SWIFT_HEADER): string {
  const importLines = [...imports].sort().map((name) => `import ${name}`);
  return [header, "", ...importLines, "", blocks.join("\n\n"), ""].join("\n");
}

export function indent(lines: string[], depth = 1): string[] {
  const prefix = "    ".repeat(depth);
  return lines.map((line) => (line === "" ? "" : `${prefix}${line}`));
}

export function block(header: string, body: string[]): string {
  return [`${header} {`, ...indent(body), "}"].join("\n");
}

export function deprecation(token: TokenBase, renamedTo: (target: string) => string): string[] {
  return token.deprecated === undefined ? [] : [`@available(*, deprecated, renamed: "${renamedTo(token.deprecated.renamedTo)}")`];
}

export function currentCamel(token: TokenBase): string {
  return token.deprecated === undefined ? token.name.camel : toCamelName(token.deprecated.renamedTo);
}

export function staticLet(token: TokenBase, type: string | undefined, value: () => string[]): string[] {
  const declaration = `public static let ${swiftIdentifier(token.name.camel)}${type === undefined ? "" : `: ${type}`} = `;
  if (token.deprecated !== undefined) {
    return [...deprecation(token, toCamelName), `${declaration}${swiftIdentifier(currentCamel(token))}`];
  }
  const [first = "", ...rest] = value();
  return [`${declaration}${first}`, ...rest];
}

export function active<T extends TokenBase>(tokens: T[]): T[] {
  return tokens.filter((token) => token.deprecated === undefined);
}

export function tokenList(type: string, entries: string[], name = "allTokens"): string[] {
  if (entries.length === 0) {
    return [`public static let ${name}: [${type}] = []`];
  }
  return [`public static let ${name}: [${type}] = [`, ...indent(entries.map((entry) => `${entry},`)), "]"];
}
