export const XML_HEADER = "<!-- Generated by tools/codegen from design/source and design/extensions. Do not edit. -->";

export function resourcesFile(entries: string[], attributes: string[] = []): string {
  const open = attributes.length === 0 ? "<resources>" : `<resources ${attributes.join(" ")}>`;
  return ['<?xml version="1.0" encoding="utf-8"?>', XML_HEADER, open, ...entries.map((entry) => `    ${entry}`), "</resources>", ""].join("\n");
}

export function element(tag: string, name: string, value: string, attributes: Record<string, string> = {}): string {
  const extra = Object.entries(attributes)
    .map(([key, attribute]) => ` ${key}="${attribute}"`)
    .join("");
  return `<${tag} name="${name}"${extra}>${value}</${tag}>`;
}

export function style(name: string, items: [string, string][], parent?: string): string[] {
  const open = parent === undefined ? `<style name="${name}">` : `<style name="${name}" parent="${parent}">`;
  if (items.length === 0) {
    return [open.replace(/>$/, " />")];
  }
  return [open, ...items.map(([key, value]) => `    <item name="${key}">${value}</item>`), "</style>"];
}
