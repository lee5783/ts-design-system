public enum DemoStrings {
    public static func string(_ key: DemoStringKey) -> String {
        string(rawKey: key.rawValue)
    }

    public static func tapCount(_ count: Int) -> String {
        String(format: string(rawKey: "demo.component.tap-count"), locale: .current, count)
    }

    public static func dialogResult(_ result: String) -> String {
        String(format: string(rawKey: "demo.component.result"), locale: .current, result)
    }

    public static func refusedCount(_ count: Int) -> String {
        String(format: string(rawKey: "demo.component.refused-count"), locale: .current, count)
    }

    public static func queuedCount(_ count: Int) -> String {
        String(format: string(rawKey: "demo.component.queued-count"), locale: .current, count)
    }

    public static func pageTitle(_ page: DemoPageID) -> String {
        string(rawKey: "demo.page.\(page.rawValue)")
    }

    public static func sectionTitle(_ section: DemoSection.ID) -> String {
        string(rawKey: "demo.section.\(section.rawValue)")
    }

    public static func themeToggleLabel(_ theme: DemoTheme) -> String {
        String(format: string(rawKey: "demo.theme.toggle"), locale: .current, themeTitle(theme))
    }

    public static func themeTitle(_ theme: DemoTheme) -> String {
        string(rawKey: "demo.theme.\(theme.rawValue)")
    }

    public static func textSizeTitle(_ textSize: DemoTextSize) -> String {
        string(rawKey: "demo.text-size.\(textSize.rawValue)")
    }

    static func string(rawKey: String) -> String {
        String(localized: String.LocalizationValue(rawKey), table: "DemoStrings", bundle: .module)
    }
}
